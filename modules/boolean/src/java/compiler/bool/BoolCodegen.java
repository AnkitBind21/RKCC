package compiler.bool;

import compiler.bool.Ast.*;

import java.util.List;

/**
 * Phase 4: NASM x86-64 (Intel syntax) code generation for a validated Boolean program.
 *
 * <h3>Conventions</h3>
 * <ul>
 *   <li>true = 1, false = 0; every boolean is one byte in {@code .data}, named {@code b_<javaName>}.</li>
 *   <li>The value of any expression is left in {@code al} and is always exactly 0 or 1.</li>
 *   <li>{@code rax} is the accumulator, {@code rcx} (cl) holds a spilled right operand.
 *       Nested operands are saved with push/pop; the stack is balanced and no calls are made.</li>
 *   <li>The program is emitted as {@code bool_main}, a plain routine ending in {@code ret}; it uses no
 *       libc, no OS call and preserves nothing but rsp, so a host compiler can embed it.</li>
 *   <li>Optional "standalone" mode adds a Linux x86-64 {@code _start} that calls bool_main,
 *       prints {@code name=0/1} for every variable with the write syscall and exits.</li>
 *   <li>Both modes end with a {@code .note.GNU-stack} section marking the stack non-executable.
 *       Without it ld warns "implies executable stack" and the linked program gets an RWE stack.
 *       The section is ELF-specific: assemble with {@code nasm -f elf64}.</li>
 * </ul>
 */
public final class BoolCodegen {

    /** @param standalone add the Linux _start + variable dump; @param comments echo Java source as comments */
    public record Options(boolean standalone, boolean comments) {
        public static Options library() { return new Options(false, true); }
        public static Options linuxStandalone() { return new Options(true, true); }
    }

    /** ELF marker: this object does not need an executable stack. */
    static final String GNU_STACK_NOTE = "section .note.GNU-stack noalloc noexec nowrite progbits";

    private final StringBuilder out = new StringBuilder();
    private final Options options;
    private int labelCounter = 0;

    private BoolCodegen(Options options) {
        this.options = options;
    }

    public static String generate(Program program, List<String> variables, Options options) {
        BoolCodegen g = new BoolCodegen(options);
        g.emitProgram(program, variables);
        return g.out.toString();
    }

    /** NASM symbol for a Java variable; the prefix keeps it clear of registers, mnemonics and our labels. */
    static String symbol(String javaName) {
        return "b_" + javaName;
    }

    // ---- program layout -------------------------------------------------

    private void emitProgram(Program program, List<String> variables) {
        line("; Generated by the RKCC Boolean module");
        line("; Target: x86-64, NASM, Intel syntax.  true = 1, false = 0 (one byte per boolean).");
        line("bits 64");
        line("default rel");
        line("");
        line("section .data");
        for (String v : variables) {
            line(String.format("%-12s db 0", symbol(v) + ":"));
        }
        StringBuilder dumpOffsets = new StringBuilder();
        if (options.standalone()) {
            line("dump_buf:");
            int offset = 0;
            for (String v : variables) {
                String text = v + "=";
                line("    db \"" + text + "0\", 10");
                dumpOffsets.append(String.format("    mov al, [%s]%n    add al, '0'%n    mov [dump_buf + %d], al%n",
                        symbol(v), offset + text.length()));
                offset += text.length() + 2;
            }
            line("dump_len equ $ - dump_buf");
        }
        line("");
        line("section .text");
        line("global bool_main");
        line("bool_main:");
        for (Stmt s : program.statements()) {
            emitStatement(s);
        }
        ins("ret");

        if (options.standalone()) {
            line("");
            line("global _start");
            line("_start:");
            ins("call bool_main");
            out.append(dumpOffsets);
            ins("mov eax, 1              ; sys_write");
            ins("mov edi, 1              ; stdout");
            ins("lea rsi, [dump_buf]");
            ins("mov edx, dump_len");
            ins("syscall");
            ins("mov eax, 60             ; sys_exit");
            ins("xor edi, edi");
            ins("syscall");
        }

        line("");
        line("; Non-executable stack marker (ELF); prevents the linker's executable-stack warning.");
        line(GNU_STACK_NOTE);
    }

    // ---- statements -------------------------------------------------------

    private void emitStatement(Stmt s) {
        if (options.comments()) line("    ; " + s.source());
        switch (s) {
            case Decl d -> {
                if (d.init() != null) {
                    genExpr(d.init());
                    ins("mov [" + symbol(d.name()) + "], al");
                }                                   // no initialiser: storage is already 0
            }
            case Assign a -> {
                Expr value = a.op() == AssignOp.ASSIGN
                        ? a.value()
                        : new Binary(a.op().binOp, new VarRef(a.name(), a.pos()), a.value(), a.pos()); // a op= e  ==  a = a op e
                genExpr(value);
                ins("mov [" + symbol(a.name()) + "], al");
            }
        }
    }

    // ---- expressions: result in AL --------------------------------------------

    private void genExpr(Expr e) {
        switch (e) {
            case BoolLit b -> ins("mov al, " + (b.value() ? 1 : 0));
            case VarRef v -> ins("mov al, [" + symbol(v.name()) + "]");
            case Not n -> {
                genExpr(n.operand());
                ins("xor al, 1               ; logical NOT (value is 0/1)");
            }
            case Binary b -> genBinary(b);
            default -> throw new IllegalStateException(
                    "non-boolean expression reached code generation: " + e);   // checker prevents this
        }
    }

    private void genBinary(Binary b) {
        switch (b.op()) {
            case LOGICAL_AND -> genShortCircuit(b, "jz", "&&: left is false, result stays 0");
            case LOGICAL_OR -> genShortCircuit(b, "jnz", "||: left is true, result stays 1");
            default -> genEager(b);
        }
    }

    /** a && b / a || b: the right operand's code is skipped when the left decides the result. */
    private void genShortCircuit(Binary b, String jump, String why) {
        String end = newLabel("sc_end");
        genExpr(b.left());
        ins("test al, al");
        ins(jump + " " + end + "            ; " + why);
        genExpr(b.right());
        line(end + ":");
    }

    /** &, |, ^, ==, != : both operands are always evaluated. */
    private void genEager(Binary b) {
        String operand = leafOperand(b.right());
        genExpr(b.left());
        if (operand == null) {                       // complex right side: spill left, evaluate right
            ins("push rax");
            genExpr(b.right());
            ins("mov cl, al");
            ins("pop rax");
            operand = "cl";
        }
        switch (b.op()) {
            case BIT_AND -> ins("and al, " + operand);
            case BIT_OR -> ins("or al, " + operand);
            case XOR -> ins("xor al, " + operand);
            case EQ -> { ins("cmp al, " + operand); ins("sete al"); }
            case NE -> { ins("cmp al, " + operand); ins("setne al"); }
            default -> throw new IllegalStateException("not an eager operator: " + b.op());
        }
    }

    /** A literal or variable can be used directly as an instruction operand. */
    private static String leafOperand(Expr e) {
        return switch (e) {
            case BoolLit b -> b.value() ? "1" : "0";
            case VarRef v -> "[" + symbol(v.name()) + "]";
            default -> null;
        };
    }

    // ---- output helpers -------------------------------------------------------

    private String newLabel(String hint) {
        return ".L" + hint + "_" + (++labelCounter);    // local to bool_main; counter makes it unique
    }

    private void ins(String text) { out.append("    ").append(text).append('\n'); }

    private void line(String text) { out.append(text).append('\n'); }
}
